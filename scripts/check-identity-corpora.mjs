#!/usr/bin/env node
// Proves that the committed identity corpora (IDENTITY-PROFILE-01 §12, task
// LFCP-04-403) are exactly what their generators produce. Each generator runs
// into a temporary directory and its files are compared byte for byte:
//
// - test-vectors/identity-01/IDENTITY-PROFILE-TEST-VECTORS-01.{json,md}, by
//   generate_identity_profile_vectors_01.mjs with the pinned
//   @automerge/automerge;
// - test-vectors/identity-01/IDENTITY-FLOW-FIXTURES-01.{json,md}, by
//   generate_identity_flow_fixtures_01.py (Python standard library only);
// - test-vectors/lfcp-wire-01/LFCP-IDENTITY-TEST-VECTORS-01.{json,md}, by
//   generate_lfcp_identity_test_vectors_01.py, when the Python module
//   `cryptography` is available (as for LFCP-TEST-VECTORS-01, the generator
//   needs it; set LFCP_PYTHON to a Python that has it, for example .venv/bin/python).
//   Without it the check says so and is skipped, not failed.

import { execFileSync, spawnSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const python = process.env.LFCP_PYTHON || "python3";
const pinned = JSON.parse(readFileSync(join(root, "package.json"), "utf8")).devDependencies["@automerge/automerge"];
const installed = JSON.parse(readFileSync(join(root, "node_modules", "@automerge", "automerge", "package.json"), "utf8")).version;

const corpora = [
  { dir: "test-vectors/lfcp-wire-01", base: "LFCP-IDENTITY-TEST-VECTORS-01", cmd: [python, "generate_lfcp_identity_test_vectors_01.py"], needs: "cryptography" },
  { dir: "test-vectors/identity-01", base: "IDENTITY-PROFILE-TEST-VECTORS-01", cmd: ["node", "generate_identity_profile_vectors_01.mjs"] },
  { dir: "test-vectors/identity-01", base: "IDENTITY-FLOW-FIXTURES-01", cmd: [python, "generate_identity_flow_fixtures_01.py"] },
];

let failed = false;
if (installed !== pinned) {
  console.log(`FAIL  @automerge/automerge ${installed} installed, ${pinned} pinned; run pnpm install --frozen-lockfile`);
  process.exit(1);
}
for (const c of corpora) {
  if (c.needs && spawnSync(python, ["-c", `import ${c.needs}`], { stdio: "ignore" }).status !== 0) {
    console.log(`skip  ${c.base}: ${python} lacks the module ${c.needs} (set LFCP_PYTHON)`);
    continue;
  }
  const out = mkdtempSync(join(tmpdir(), "lfcp-identity-corpus-"));
  try {
    const [cmd, script] = c.cmd;
    execFileSync(cmd, [join(root, c.dir, script), "--out-dir", out], { stdio: ["ignore", "ignore", "inherit"], env: { ...process.env, PYTHONDONTWRITEBYTECODE: "1" } });
    const diff = ["json", "md"].filter((ext) => !readFileSync(join(out, `${c.base}.${ext}`)).equals(readFileSync(join(root, c.dir, `${c.base}.${ext}`))));
    const doc = JSON.parse(readFileSync(join(root, c.dir, `${c.base}.json`), "utf8"));
    console.log(`${diff.length ? "FAIL" : "ok  "}  ${c.base}: ${doc.cases.length} cases, ${diff.length ? `${diff.join(" and ")} differ from the generator` : "regenerated byte-identically"}`);
    failed ||= diff.length > 0;
  } finally {
    rmSync(out, { recursive: true, force: true });
  }
}
process.exit(failed ? 1 : 0);
