#!/usr/bin/env node
// Checks the shared sections reference corpus
// (test-vectors/shared-sections-01/, LFCP-02-008):
//
// 1. SHARED-SECTIONS-TEST-VECTORS-01.json is an lfcp-vector-format/1 suite,
//    checked against the format by scripts/validate-vectors.mjs; here, its
//    engine is the pinned one;
// 2. the generator, run with the pinned @automerge/automerge, reproduces
//    it byte for byte (expected values are never regenerated to suit an
//    implementation);
// 3. the reference verifier replays every stored change and save image
//    (normal order, reverse order with duplicates, Snapshot plus tail) and
//    reaches each case's expected state and assertions;
// 4. MARKDOWN-SECTIONS-FIXTURES-01.json and its markdown-files/ tree match
//    their schema and generator, and pass the reference lexical checks.
//
// The verifier writes a report; it runs on a temporary copy, so the
// committed directory stays as it is.

import { execFileSync } from "node:child_process";
import { copyFileSync, cpSync, mkdtempSync, readFileSync, readdirSync, rmSync, statSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import Ajv2020 from "ajv/dist/2020.js";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "test-vectors", "shared-sections-01");
const name = "SHARED-SECTIONS-TEST-VECTORS-01.json";
const suite = JSON.parse(readFileSync(join(dir, name), "utf8"));
const pinned = JSON.parse(readFileSync(join(root, "package.json"), "utf8")).devDependencies["@automerge/automerge"];

let failed = false;
const fail = (message) => {
  console.log(`FAIL  ${message}`);
  failed = true;
};

const engine = suite.suite.conventions.engine_version;
if (engine !== pinned) fail(`${name}: generated with ${engine}, ${pinned} pinned`);

const out = mkdtempSync(join(tmpdir(), "lfcp-shared-sections-"));
try {
  execFileSync("node", [join(dir, "generator", "generate-vectors.mjs"), out], { stdio: ["ignore", "ignore", "inherit"] });
  if (!readFileSync(join(out, name)).equals(readFileSync(join(dir, name)))) fail(`${name} differs from its generator`);
  const replay = mkdtempSync(join(tmpdir(), "lfcp-shared-sections-replay-"));
  try {
    copyFileSync(join(dir, name), join(replay, name));
    execFileSync("node", [join(dir, "generator", "verify-vectors.mjs"), replay], { stdio: ["ignore", "ignore", "inherit"] });
  } catch (e) {
    fail(`${name}: reference replay: ${e.message.split("\n")[0]}`);
  } finally {
    rmSync(replay, { recursive: true, force: true });
  }
} finally {
  rmSync(out, { recursive: true, force: true });
}
// 4. The Markdown fixtures.
const mdName = "MARKDOWN-SECTIONS-FIXTURES-01.json";
const mdSuite = JSON.parse(readFileSync(join(dir, mdName), "utf8"));
const mdSchema = JSON.parse(readFileSync(join(dir, "schemas", "markdown-fixtures.schema.json"), "utf8"));
const validateMd = new Ajv2020({ allErrors: true, strict: false }).compile(mdSchema);
if (!validateMd(mdSuite)) fail(`${mdName}: schema: ${JSON.stringify(validateMd.errors.slice(0, 3))}`);
/** Every file under `base`, relative path to bytes. */
const tree = (base) => {
  const files = new Map();
  const walk = (rel) => {
    for (const entry of readdirSync(join(base, rel))) {
      const r = rel ? join(rel, entry) : entry;
      if (statSync(join(base, r)).isDirectory()) walk(r);
      else files.set(r, readFileSync(join(base, r)));
    }
  };
  walk("");
  return files;
};
const mdOut = mkdtempSync(join(tmpdir(), "lfcp-shared-sections-md-"));
try {
  execFileSync("node", [join(dir, "generator", "generate-markdown.mjs"), mdOut], { stdio: ["ignore", "ignore", "inherit"] });
  if (!readFileSync(join(mdOut, mdName)).equals(readFileSync(join(dir, mdName)))) fail(`${mdName} differs from its generator`);
  const want = tree(join(mdOut, "markdown-files"));
  const have = tree(join(dir, "markdown-files"));
  if (want.size !== have.size || [...want].some(([k, v]) => !have.get(k)?.equals(v))) fail("markdown-files/ differs from its generator");
  const check = mkdtempSync(join(tmpdir(), "lfcp-shared-sections-md-check-"));
  try {
    copyFileSync(join(dir, mdName), join(check, mdName));
    cpSync(join(dir, "markdown-files"), join(check, "markdown-files"), { recursive: true });
    execFileSync("node", [join(dir, "generator", "verify-markdown.mjs"), check], { stdio: ["ignore", "ignore", "inherit"] });
  } catch (e) {
    fail(`${mdName}: reference checks: ${e.message.split("\n")[0]}`);
  } finally {
    rmSync(check, { recursive: true, force: true });
  }
} finally {
  rmSync(mdOut, { recursive: true, force: true });
}
if (!failed) {
  console.log(
    `ok    ${name}: ${suite.cases.length} cases, @automerge/automerge ${engine}, ` +
      "regenerated byte-identically, replayed by the reference verifier",
  );
  console.log(`ok    ${mdName}: ${mdSuite.fixtures.length} fixtures, schema-valid, regenerated byte-identically, reference lexical checks pass`);
}
process.exit(failed ? 1 : 0);
