#!/usr/bin/env node
// Proves that the committed Automerge reference corpus is exactly what its
// pinned generator produces: regenerates
// test-vectors/shared-objects-01/SHARED-OBJECTS-AUTOMERGE-REFERENCE-01.json
// into a temporary directory with @automerge/automerge (pinned in
// package.json) and compares the bytes.

import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "test-vectors", "shared-objects-01");
const name = "SHARED-OBJECTS-AUTOMERGE-REFERENCE-01.json";
const pinned = JSON.parse(readFileSync(join(root, "package.json"), "utf8")).devDependencies["@automerge/automerge"];
const installed = JSON.parse(
  readFileSync(join(root, "node_modules", "@automerge", "automerge", "package.json"), "utf8"),
).version;

const out = mkdtempSync(join(tmpdir(), "lfcp-automerge-corpus-"));
try {
  if (installed !== pinned) {
    console.log(`FAIL  @automerge/automerge ${installed} installed, ${pinned} pinned; run pnpm install --frozen-lockfile`);
    process.exit(1);
  }
  execFileSync("node", [join(dir, "generate_automerge_reference_01.mjs"), "--out-dir", out], {
    stdio: ["ignore", "ignore", "inherit"],
  });
  const same = readFileSync(join(out, name)).equals(readFileSync(join(dir, name)));
  const corpus = JSON.parse(readFileSync(join(dir, name), "utf8"));
  const changes = corpus.scenarios.reduce((n, s) => n + s.changes.length, 0);
  console.log(
    `${same ? "ok  " : "FAIL"}  ${name}: ${corpus.scenarios.length} scenarios, ${changes} changes, ` +
      `@automerge/automerge ${installed}${same ? ", regenerated byte-identically" : " differs from its generator"}`,
  );
  process.exit(same ? 0 : 1);
} finally {
  rmSync(out, { recursive: true, force: true });
}
